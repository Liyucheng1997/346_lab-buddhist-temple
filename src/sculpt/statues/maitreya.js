// 弥勒（布袋和尚）：袒胸露腹、开怀大笑，右手持念珠搭膝，左手按布袋，右膝屈起。通身贴金。
import { Sculpt } from '../sdf.js';
import { Frame, head, arm, handAt, beads, ridge, V } from '../anatomy.js';
import { palette } from './palette.js';

export function maitreya(p = {}) {
  const S = new Sculpt(palette({ bag: { color: '#c9a860', cls: 'gold' } }));
  const F = new Frame(S);
  const robe = 'robe';

  // ---------------- 下身：左腿盘坐，右膝竖起 ----------------
  F.ellipsoid([0, 0.1, 0.06], [0.5, 0.12, 0.3], { mat: robe, k: 0.08 });
  F.cone([0.12, 0.14, -0.05], [0.44, 0.12, 0.18], 0.14, 0.11, { mat: robe, k: 0.07 });   // 左大腿（盘）
  F.cone([0.42, 0.1, 0.22], [-0.05, 0.1, 0.33], 0.085, 0.07, { mat: robe, k: 0.05 });    // 左小腿
  F.ellipsoid([-0.02, 0.14, 0.36], [0.1, 0.035, 0.05], { mat: 'skin', k: 0.02, rot: [0, 0.3, 0] }); // 左足
  F.cone([-0.14, 0.14, -0.04], [-0.3, 0.5, 0.2], 0.15, 0.1, { mat: robe, k: 0.07 });      // 右大腿（竖起）
  F.cone([-0.3, 0.5, 0.2], [-0.33, 0.08, 0.32], 0.1, 0.085, { mat: robe, k: 0.06 });     // 右小腿
  F.ellipsoid([-0.33, 0.05, 0.42], [0.07, 0.04, 0.11], { mat: 'skin', k: 0.02 });         // 右足
  F.sphere([-0.3, 0.52, 0.22], 0.11, { mat: 'skin', k: 0.05 });                           // 右膝（露出）
  F.ellipsoid([0, 0.03, 0.3], [0.4, 0.05, 0.08], { mat: robe, k: 0.05 });                 // 悬裳
  // ---------------- 大肚与躯干（后仰） ----------------
  F.sphere([0, 0.36, 0.08], 0.3, { mat: 'skin', k: 0.1 });                                 // 腹
  F.ellipsoid([0, 0.55, -0.02], [0.3, 0.17, 0.2], { mat: 'skin', k: 0.12 });              // 胸
  F.mirror((m) => m.ellipsoid([0.13, 0.58, 0.14], [0.11, 0.08, 0.06], { mat: 'skin', k: 0.06 })); // 胸肌
  F.sphere([0, 0.37, 0.37], 0.016, { op: 'sub', k: 0.01 });                                // 脐
  F.ellipsoid([0, 0.66, -0.1], [0.33, 0.14, 0.17], { mat: robe, k: 0.1 });                // 肩背的袈裟
  F.capsule([-0.2, 0.68, -0.08], [0.2, 0.68, -0.08], 0.1, { mat: robe, k: 0.1 });
  F.cone([0, 0.68, -0.02], [0, 0.86, 0.0], 0.09, 0.08, { mat: 'skin', k: 0.05 });         // 粗颈
  F.torus([0, 0.8, 0.0], 0.085, 0.006, { mat: 'skin', k: 0.006 });
  // 袈裟自两肩垂落，敞于腹部两侧
  F.mirror((m) => {
    m.ribbon([[0.2, 0.75, 0.0], [0.33, 0.6, 0.12], [0.4, 0.4, 0.2], [0.42, 0.2, 0.3]], [0.09, 0.1, 0.11, 0.1], 0.04, { mat: robe, k: 0.05, up: [0, 0, 1] });
    ridge(m, [[0.2, 0.75, 0], [0.3, 0.62, 0], [0.37, 0.42, 0], [0.4, 0.22, 0]], [0, 0, 1], 0.012, { mat: 'robeEdge', taper: false, lift: -0.005, far: 0.5 });
  });
  // ---------------- 手臂 ----------------
  const sleeve = { sleeve: 0.1, ru: 0.09, rf: 0.072, rw: 0.048, upper: 0.28, fore: 0.26, mat: robe };
  // 右臂（-x）搭在竖起的右膝上，手握念珠垂下
  const r = arm(F, [-0.3, 0.64, -0.02], [-0.36, 0.56, 0.3], { ...sleeve, pole: [-1, 0, -0.5] });
  handAt(F, r.wrist, [0.1, -0.9, 0.4], [0, 0.4, 1], 'flat', 'skin', 1.1, { curl: 0.5 });
  beads(F, [-0.36, 0.42, 0.36], 0.09, 0.016, 22, [0.3, 0, 0.2]);
  // 左臂（+x）按在身侧的布袋上
  const l = arm(F, [0.3, 0.64, -0.02], [0.52, 0.22, 0.12], { ...sleeve, pole: [1, 0, -0.6] });
  handAt(F, l.wrist, [0.3, -0.8, 0.5], [0, 0.5, 1], 'flat', 'skin', 1.1, { left: true, curl: 0.2 });
  // 布袋：扎口的大布囊
  F.ellipsoid([0.58, 0.14, 0.06], [0.2, 0.15, 0.2], { mat: 'bag', k: 0.05, folds: { dir: [0, 1, 0.3], freq: 40, amp: 0.006 } });
  F.cone([0.6, 0.26, 0.04], [0.62, 0.36, 0.02], 0.07, 0.04, { mat: 'bag', k: 0.03 });
  F.torus([0.615, 0.33, 0.025], 0.045, 0.012, { mat: 'robeEdge', k: 0.006 });
  // ---------------- 头：光头、大笑 ----------------
  const H = F.child([0, 0.99, 0.05], 0.3, [-0.04, 0, 0]);
  head(H, { style: 'maitreya', fat: 1.0, smile: 0.9, mouthOpen: 0.9, teeth: true, browPaint: true, age: 0.2 });

  const headBox = [[-0.18, 0.8, -0.14], [0.18, 1.25, 0.22]];
  const parts = [
    { name: 'body', bmin: [-0.6, -0.02, -0.32], bmax: [0.85, 0.85, 0.52], h: 0.0065, exclude: [headBox] },
    { name: 'head', bmin: headBox[0], bmax: headBox[1], h: 0.0023 },
  ];
  return { S, parts, props: [], height: 1.22, name: '弥勒佛' };
}
