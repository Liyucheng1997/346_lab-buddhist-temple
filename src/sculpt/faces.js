// 佛面：按唐宋以降汉传造像的“方圆丰满、眉如新月、垂目含笑”比例塑造。
// 局部单位：眼睛 y=0，下颌 y≈-0.5，颅顶 y≈0.5，面朝 +z。
import { V } from './anatomy.js';

// 椭球面上的斐波那契均匀点（用于螺发）
function fibOnEllipsoid(c, r, n, seed = 0) {
  const pts = [];
  const g = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < n; i++) {
    const y = 1 - (2 * (i + 0.5)) / n;
    const rad = Math.sqrt(1 - y * y);
    const a = g * (i + seed);
    pts.push([c[0] + r[0] * rad * Math.cos(a), c[1] + r[1] * y, c[2] + r[2] * rad * Math.sin(a)]);
  }
  return pts;
}

export function buddhaFace(F, opt = {}) {
  const skin = opt.skin || 'skin';
  const smile = opt.smile ?? 0.25;
  const K = 0.12;

  // ---------- 大体块 ----------
  F.ellipsoid([0, 0.08, -0.04], [0.37, 0.43, 0.42], { mat: skin, k: K });          // 颅
  F.ellipsoid([0, -0.1, 0.06], [0.345, 0.36, 0.32], { mat: skin, k: 0.14 });        // 面
  F.ellipsoid([0, -0.3, 0.05], [0.285, 0.2, 0.28], { mat: skin, k: K });            // 颊颌
  F.ellipsoid([0, -0.44, 0.19], [0.14, 0.09, 0.11], { mat: skin, k: 0.08 });        // 颏
  F.ellipsoid([0, 0.23, 0.2], [0.3, 0.17, 0.18], { mat: skin, k: 0.1 });            // 额（宽而平）
  F.mirror((m) => m.ellipsoid([0.18, -0.14, 0.2], [0.12, 0.11, 0.09], { mat: skin, k: 0.11 })); // 颊

  // ---------- 眉弓（新月形，微微上扬） ----------
  F.mirror((m) => m.chain([[0.03, 0.085, 0.37], [0.16, 0.12, 0.33], [0.3, 0.1, 0.22]], [0.024, 0.028, 0.02], { mat: skin, k: 0.07 }));

  // 细长的彩绘眉
  F.mirror((m) => m.ribbon([[0.04, 0.095, 0], [0.11, 0.125, 0], [0.2, 0.13, 0], [0.29, 0.11, 0]].map((q) => m.surface(q, [0, 0, 1], 0.6)), 0.012, 0.03, { op: 'paint', mat: 'brow', up: [0, 0, 1] }));

  // ---------- 眼（眼睑平缓饱满，眼缝细长，外眼角上挑） ----------
  F.mirror((m) => {
    m.ellipsoid([0.155, 0.0, 0.345], [0.1, 0.05, 0.05], { op: 'sub', k: 0.07 });                     // 浅眼窝
    m.ellipsoid([0.155, -0.01, 0.3], [0.085, 0.05, 0.06], { mat: skin, k: 0.03 });                   // 眼球体
    m.ellipsoid([0.155, 0.012, 0.325], [0.105, 0.03, 0.05], { mat: skin, k: 0.03, rot: [0, 0, 0.1] }); // 上睑
    m.ellipsoid([0.155, -0.04, 0.315], [0.085, 0.018, 0.045], { mat: skin, k: 0.03 });               // 下睑
    m.ellipsoid([0.158, -0.014, 0.36], [0.1, 0.0055, 0.03], { op: 'sub', k: 0.004, rot: [0, 0, 0.14] }); // 眼缝
    m.ellipsoid([0.158, -0.011, 0.362], [0.102, 0.0095, 0.03], { op: 'paint', mat: 'eyeLine', rot: [0, 0, 0.14] }); // 眼线
  });

  // ---------- 鼻 ----------
  F.cone([0, 0.07, 0.37], [0, -0.16, 0.435], 0.034, 0.048, { mat: skin, k: 0.04 });
  F.sphere([0, -0.18, 0.432], 0.046, { mat: skin, k: 0.03 });
  F.mirror((m) => {
    m.ellipsoid([0.062, -0.195, 0.385], [0.046, 0.036, 0.042], { mat: skin, k: 0.03 });
    m.ellipsoid([0.04, -0.222, 0.415], [0.018, 0.011, 0.016], { op: 'sub', k: 0.012 });
  });
  F.ellipsoid([0, -0.24, 0.42], [0.016, 0.03, 0.012], { op: 'sub', k: 0.012 }); // 人中

  // ---------- 口 ----------
  const my = -0.29;
  F.ellipsoid([0, my + 0.02, 0.385], [0.09, 0.025, 0.04], { mat: skin, k: 0.025 });
  F.ellipsoid([0, my - 0.025, 0.375], [0.075, 0.028, 0.04], { mat: skin, k: 0.025 });
  F.ellipsoid([0, my - 0.002, 0.412], [0.09, 0.0035, 0.025], { op: 'sub', k: 0.004 });
  F.mirror((m) => m.sphere([0.098, my + 0.004 + smile * 0.02, 0.352], 0.013, { op: 'sub', k: 0.022 })); // 嘴角窝
  F.ellipsoid([0, my - 0.062, 0.37], [0.055, 0.012, 0.03], { op: 'sub', k: 0.018 });                  // 唇下沟
  F.ellipsoid([0, my - 0.004, 0.402], [0.072, 0.022, 0.028], { op: 'paint', mat: 'lip' });

  // ---------- 耳（长垂耳轮） ----------
  F.mirror((m) => {
    m.ellipsoid([0.36, 0.02, -0.01], [0.055, 0.19, 0.11], { mat: skin, k: 0.03, rot: [0, -0.3, 0.06] });
    m.ellipsoid([0.395, 0.05, 0.02], [0.03, 0.12, 0.07], { op: 'sub', k: 0.02, rot: [0, -0.3, 0.06] });
    m.cone([0.37, -0.12, 0.02], [0.355, -0.46, 0.06], 0.05, 0.058, { mat: skin, k: 0.03 });
    m.ellipsoid([0.385, -0.34, 0.07], [0.012, 0.08, 0.024], { op: 'sub', k: 0.01 });
  });

  // ---------- 螺发（离散的螺髻颗粒，发际线中央微尖） ----------
  const hc = [0, 0.1, -0.04], hr = [0.385, 0.445, 0.455];
  const hairline = (p) => 0.27 + 0.35 * (p[2] - 0.33) - 0.05 * Math.exp(-((p[0] / 0.1) ** 2));
  // 底层发帽：略小于颗粒层，边缘藏在颗粒之下
  F.ellipsoid(hc, [hr[0] + 0.008, hr[1] + 0.008, hr[2] + 0.008], { mat: 'hair', k: 0.02, clip: [[0, 0.262, 0.33], [0, -1, 0.35]] });
  F.ellipsoid([0, 0.1, -0.04], [0.393, 0.385, 0.463], { mat: 'hair', k: 0.02, clip: [[0, 0, 0.02], [0, 0, 1]] });
  for (const p of fibOnEllipsoid(hc, [hr[0] + 0.002, hr[1] + 0.002, hr[2] + 0.002], 1050)) {
    const earZone = Math.abs(p[0]) > 0.29 && p[1] < 0.2 && p[2] > -0.17;
    if (earZone) continue;
    const ok = p[2] > 0.02 ? p[1] > hairline(p) : p[1] > -0.22;
    if (!ok) continue;
    F.sphere(p, 0.027, { mat: 'hair', k: 0.006 });
  }
  // 肉髻
  const uc = [0, 0.5, -0.07], ur = [0.24, 0.2, 0.25];
  F.ellipsoid(uc, ur, { mat: 'hair', k: 0.06 });
  for (const p of fibOnEllipsoid(uc, [ur[0] + 0.003, ur[1] + 0.003, ur[2] + 0.003], 150, 7)) {
    if (p[1] < 0.5) continue;
    F.sphere(p, 0.028, { mat: 'hair', k: 0.006 });
  }
  F.sphere([0, 0.42, 0.21], 0.04, { mat: 'jewel', k: 0.008 });  // 髻珠
  F.sphere([0, 0.14, 0.37], 0.02, { mat: 'urna', k: 0.004 });   // 白毫
}
